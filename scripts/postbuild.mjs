/**
 * Runs after both Vite builds:
 *  1. dist/_redirects: the secret portal path + admin routes, direct .html access blocked.
 *  2. dist/_headers: admin CSP allowing ONLY this project's Supabase origin.
 *  3. Secret scan of dist/ (fails the build on any leak).
 *
 * Netlify does not serve _redirects/_headers to visitors, so the key in _redirects stays private.
 */
import { existsSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const onNetlify = Boolean(process.env.NETLIFY || process.env.CONTEXT);
// Locally / in CI, pick up .env (Netlify injects real env vars instead). Existing env wins.
if (!onNetlify && existsSync('.env')) process.loadEnvFile('.env');
const key = process.env.PORTAL_KEY ?? '';
const supabaseUrl = process.env.VITE_SUPABASE_URL ?? '';

function fail(msg) {
  console.error(`\n✖ postbuild: ${msg}\n`);
  process.exit(1);
}

if (key && !/^[A-Za-z0-9_-]{16,128}$/.test(key)) fail('PORTAL_KEY must be 16–128 URL-safe characters (A–Z a–z 0–9 _ -).');
if (onNetlify && !key) fail('PORTAL_KEY is not set in Netlify environment variables.');
if (onNetlify && !supabaseUrl) fail('VITE_SUPABASE_URL is not set in Netlify environment variables.');

const redirects = [
  '# Generated by scripts/postbuild.mjs. Do not edit.',
  '/portal.html     /404.html     404!',
  '/admin.html      /404.html     404!',
  '/index.html      /404.html     404!',
  ...(key ? [`/s/${key}        /portal.html  200!`, `/s/${key}/       /portal.html  200!`] : []),
  '/admin           /admin.html   200!',
  '/admin/*         /admin.html   200!',
  '/auth/callback   /admin.html   200!',
  '/auth/confirm    /admin.html   200!',
  '',
].join('\n');
writeFileSync('dist/_redirects', redirects);

let supabaseOrigin = '';
try {
  supabaseOrigin = supabaseUrl ? new URL(supabaseUrl).origin : '';
} catch {
  fail('VITE_SUPABASE_URL is not a valid URL.');
}
const adminCsp = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self'",
  `img-src 'self' blob:${supabaseOrigin ? ' ' + supabaseOrigin : ''}`,
  "font-src 'self'",
  `connect-src 'self'${supabaseOrigin ? ' ' + supabaseOrigin : ''}`,
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  'upgrade-insecure-requests',
].join('; ');
const headers = ['/admin', '/admin/*', '/auth/callback', '/auth/confirm']
  .map((p) => `${p}\n  Content-Security-Policy: ${adminCsp}\n  Cache-Control: no-store\n`)
  .join('\n');
writeFileSync('dist/_headers', `# Generated by scripts/postbuild.mjs. Do not edit.\n${headers}`);

console.log(`postbuild: _redirects (${key ? 'portal path set' : 'NO PORTAL_KEY: portal unreachable'}), _headers (admin CSP → ${supabaseOrigin || 'self only'})`);
execFileSync(process.execPath, ['scripts/check-dist.mjs'], { stdio: 'inherit' });
